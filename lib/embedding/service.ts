import { prisma } from '@/lib/prisma';
import { OpenAIEmbeddingProvider } from './providers/openai';
import { getPriorArtEmbeddingText, getInventionEmbeddingText } from './normalization';
import { EmbeddingProvider, EmbeddingResult } from './types';

/**
 * Active Embedding Provider Singleton
 */
let activeEmbeddingProvider: EmbeddingProvider = new OpenAIEmbeddingProvider();

export function getEmbeddingProvider(): EmbeddingProvider {
  return activeEmbeddingProvider;
}

export function setEmbeddingProvider(provider: EmbeddingProvider) {
  activeEmbeddingProvider = provider;
}

/**
 * Model Consistency & Fail-Safe Guard (Requirement 5):
 * Ensures vectors generated by different models or dimensions are never mixed or compared.
 */
export function validateModelConsistency(
  storedModel?: string | null,
  storedDim?: number | null
): { valid: boolean; reason?: string } {
  const provider = getEmbeddingProvider();

  if (!storedModel) {
    return { valid: false, reason: 'Missing embedding model metadata.' };
  }

  if (!storedDim) {
    return { valid: false, reason: 'Missing embedding dimension metadata.' };
  }

  if (storedModel !== provider.model) {
    return {
      valid: false,
      reason: `Embedding model mismatch: Record used '${storedModel}', active provider uses '${provider.model}'.`,
    };
  }

  if (storedDim !== provider.dimensions) {
    return {
      valid: false,
      reason: `Embedding dimension mismatch: Record used ${storedDim}, active provider expects ${provider.dimensions}.`,
    };
  }

  return { valid: true };
}

/**
 * Generates and persists embedding for a PriorArtDocument record in PostgreSQL.
 */
export async function embedAndStorePriorArtDoc(docId: string): Promise<EmbeddingResult> {
  const doc = await prisma.priorArtDocument.findUnique({
    where: { id: docId },
  });

  if (!doc) {
    throw new Error(`PriorArtDocument not found for ID: ${docId}`);
  }

  const normalizedText = getPriorArtEmbeddingText(doc);
  const provider = getEmbeddingProvider();
  const result = await provider.embedText(normalizedText);

  // Validate output vector dimensions before DB update
  if (result.dimensions !== provider.dimensions || result.vector.length !== provider.dimensions) {
    throw new Error(
      `Fail-Safe Error: Vector dimension ${result.vector.length} does not match provider expectation ${provider.dimensions}.`
    );
  }

  // Format vector string for pgvector DDL [x, y, z...]
  const vectorStr = `[${result.vector.join(',')}]`;

  await prisma.$executeRawUnsafe(
    `UPDATE "prior_art_documents" 
     SET "embedding" = $1::vector, 
         "embeddingModel" = $2, 
         "embeddingDim" = $3, 
         "updatedAt" = CURRENT_TIMESTAMP 
     WHERE "id" = $4`,
    vectorStr,
    result.model,
    result.dimensions,
    docId
  );

  return result;
}

