/**
 * Performs Cosine Distance Vector Search against PriorArtDocument embedding index.
 * Strictly filters by active embedding model and dimension.
 */
export async function searchPriorArtByVector(
  queryVector: number[],
  limit = 5
): Promise<Array<{ id: string; publicationNumber: string; title: string; distance: number }>> {
  const provider = getEmbeddingProvider();

  if (queryVector.length !== provider.dimensions) {
    throw new Error(
      `Search Guard Error: Query vector dimension (${queryVector.length}) does not match active provider (${provider.dimensions}).`
    );
  }

  const vectorStr = `[${queryVector.join(',')}]`;

  // Filter strictly by matching embeddingModel and embeddingDim
  const results: any = await prisma.$queryRawUnsafe(
    `SELECT "id", "publicationNumber", "title", ("embedding" <=> $1::vector) AS distance 
     FROM "prior_art_documents" 
     WHERE "embeddingModel" = $2 
       AND "embeddingDim" = $3 
       AND "embedding" IS NOT NULL 
     ORDER BY distance ASC 
     LIMIT $4`,
    vectorStr,
    provider.model,
    provider.dimensions,
    limit
  );

  return results;
}
